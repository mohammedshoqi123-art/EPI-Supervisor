معادلة حساب الكمية المطلوبة:
الكمية المطلوبة = عدد السكان المستهدفين × عدد الجرعات × معامل الفاقد

معامل الفاقد (Wastage Factor):
معامل الفاقد = 100 ÷ (100 - معدل الهدر)

أمثلة:
• هدر 0% → معامل 1.0
• هدر 25% → معامل 1.33
• هدر 50% → معامل 2.0 (تضعف الكمية المطلوبة)
• هدر 75% → معامل 4.0

مثال عملي:
سؤال: ما هو معامل الفاقد لنسبة هدر 50%؟
الحساب: 100 ÷ (100 - 50) = 100 ÷ 50 = 2
